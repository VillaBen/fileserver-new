export const useI18nStore = defineStore('i18n', () => {
  const currentLocale = ref('en-US');
  const detectedLocale = ref(null);
  const updateKey = ref(0);
  const theme = ref('light');

  const messages = computed(() => translations[currentLocale.value] || translations['en-US']);

  function setLocale(locale) {
    if (translations[locale]) {
      console.log('Setting locale to:', locale);
      currentLocale.value = locale;
      localStorage.setItem('locale', locale);
      updateKey.value++;
      console.log('Locale updated, updateKey:', updateKey.value);
    } else {
      console.warn('Locale not found:', locale);
    }
  }

  function setTheme(newTheme) {
    theme.value = newTheme;
    localStorage.setItem('theme', newTheme);
    applyTheme(newTheme);
  }

  function applyTheme(currentTheme) {
    const html = document.documentElement;
    if (currentTheme === 'dark') {
      html.classList.add('dark-theme');
    } else if (currentTheme === 'system') {
      const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
      if (prefersDark) {
        html.classList.add('dark-theme');
      } else {
        html.classList.remove('dark-theme');
      }
    } else {
      html.classList.remove('dark-theme');
    }
  }

  const t = (key, params = {}) => {
    // 通过访问 updateKey 来强制建立响应式依赖
    const _ = updateKey.value;
    
    // 如果 key 不是字符串，直接返回 key
    if (typeof key !== 'string') {
      return key;
    }
    
    const locale = currentLocale.value;
    const keys = key.split('.');
    let value = translations[locale];
    
    for (const k of keys) {
      if (value && typeof value === 'object') {
        value = value[k];
      } else {
        return key;
      }
    }
    
    if (typeof value === 'string' && params && Object.keys(params).length > 0) {
      return value.replace(/\{(\w+)\}/g, (match, paramKey) => {
        return params[paramKey] || match;
      });
    }
    
    return typeof value === 'string' ? value : key;
  };

  async function detectLocale() {
    try {
      const response = await fetch('https://api.ipgeolocation.io/ipgeo?apiKey=demo');
      const data = await response.json();
      const countryCode = data.country_code2;
      
      if (countryCode === 'CN' || countryCode === 'TW' || countryCode === 'HK') {
        detectedLocale.value = 'zh-CN';
      } else {
        detectedLocale.value = 'en-US';
      }
    } catch (error) {
      detectedLocale.value = 'en-US';
    }
  }

  function init() {
    const savedLocale = localStorage.getItem('locale');
    if (savedLocale && translations[savedLocale]) {
      currentLocale.value = savedLocale;
    }
    
    const savedTheme = localStorage.getItem('theme');
    if (savedTheme) {
      theme.value = savedTheme;
      applyTheme(savedTheme);
    }
  }

  return {
    currentLocale,
    detectedLocale,
    t,
    setLocale,
    detectLocale,
    init,
    theme,
    setTheme
  };
});